# Membuat list nama gunung
nama_gunung = ["Merapi", "Semeru", "Bromo", "Rinjani", "Lawu", "Kerinci"]

# Menampilkan tiga elemen pertama
print("Tiga elemen pertama dalam list adalah:")
print(nama_gunung[:3])

# Menampilkan tiga elemen bagian tengah
print("\nTiga elemen bagian tengah dalam list adalah:")
print(nama_gunung[1:4])

# Menampilkan tiga elemen terakhir
print("\nTiga elemen terakhir dalam list adalah:")
print(nama_gunung[-3:])