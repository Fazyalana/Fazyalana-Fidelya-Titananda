def buat_kaos(ukuran="L", tulisan="Saya Suka Python"):
    print(f"Kaos ukuran {ukuran} dengan tulisan '{tulisan}'.")

# Kaos ukuran besar dengan tulisan bawaan
buat_kaos()

# Kaos ukuran sedang dengan tulisan bawaan
buat_kaos(ukuran="M")

# Kaos ukuran bebas dengan tulisan berbeda
buat_kaos(ukuran="S", tulisan="Teknik Industri")